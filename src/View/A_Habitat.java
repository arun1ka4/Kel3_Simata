    private void removePlaceholder(JTextField field, String placeholder) {
        field.addFocusListener(new java.awt.event.FocusAdapter() {
            public void focusGained(java.awt.event.FocusEvent evt) {
                if (field.getText().equals(placeholder)) {
                    field.setText("");
                }
            }
            public void focusLost(java.awt.event.FocusEvent evt) {
                if (field.getText().trim().isEmpty()) {
                    field.setText(placeholder);
                }
            }
        });
    }
    
    private void setupTable() {
        jTable1.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        jTable1.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && jTable1.getSelectedRow() >= 0) {
                loadSelectedRow();
            }
        });
    }
    
    private void loadTableData() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        List<Habitat> listHabitat = Habitat.getAllHabitat();
        for (Habitat habitat : listHabitat) {
            Object[] row = {
                habitat.getIdHabitat(),
                habitat.getNamaHabitat(),
                habitat.getLokasi(),
                habitat.getTipeEkosistem(),
                habitat.getLuasArea(),
                habitat.getKondisi()
            };
            model.addRow(row);
        }
    }
    
    private void loadSelectedRow() {
    int row = jTable1.getSelectedRow();
    if (row >= 0) {
        selectedHabitatId = (int) jTable1.getValueAt(row, 0);
        
        Habitat habitat = Habitat.getHabitatById(selectedHabitatId);
        if (habitat != null) {
            jTextField5.setText(habitat.getNamaHabitat());
            jTextField6.setText(habitat.getLokasi());
            jTextField7.setText(habitat.getTipeEkosistem());
            jTextField8.setText(String.valueOf(habitat.getLuasArea()));
            
            // Perbaikan: Gunakan try-catch untuk menghindari error
            try {
                jComboBox1.setSelectedItem(habitat.getKondisi());
            } catch (Exception e) {
                // Jika error, set ke default (index 0)
                jComboBox1.setSelectedIndex(0);
            }
        }
    }
}

