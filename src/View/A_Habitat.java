     private void handleEdit() {
    if (selectedHabitatId == -1) {
        JOptionPane.showMessageDialog(this,
            "Pilih habitat yang ingin diedit!",
            "Peringatan",
            JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    if (!validateInput()) return;
    
    try {
        Habitat habitat = new Habitat();
        habitat.setIdHabitat(selectedHabitatId);
        habitat.setNamaHabitat(getFieldText(jTextField5));
        habitat.setLokasi(getFieldText(jTextField6));
        habitat.setTipeEkosistem(getFieldText(jTextField7));
        
        String luasText = getFieldText(jTextField8);
        double luas = luasText.isEmpty() ? 0 : Double.parseDouble(luasText);
        habitat.setLuasArea(luas);
        
        // PERBAIKAN: Pastikan kondisi tidak null dan di-trim
        String kondisi = jComboBox1.getSelectedItem() != null ? 
                        jComboBox1.getSelectedItem().toString().trim() : "Baik";
        habitat.setKondisi(kondisi);
        
        if (habitat.updateHabitat()) {
            JOptionPane.showMessageDialog(this,
                "Habitat berhasil diupdate!",
                "Sukses",
                JOptionPane.INFORMATION_MESSAGE);
            clearForm();
            loadTableData();
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
            "Luas area harus berupa angka!",
            "Error",
            JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Error saat update: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE);
        logger.log(java.util.logging.Level.SEVERE, "Error update habitat", e);
    }
}
     
