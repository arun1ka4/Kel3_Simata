     private boolean validateInput() {
    String nama = getFieldText(jTextField5);
    String lokasi = getFieldText(jTextField6);
    String ekosistem = getFieldText(jTextField7);
    String luasText = getFieldText(jTextField8);
    
    // ========== VALIDASI NAMA HABITAT ==========
    if (nama.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Nama Habitat harus diisi!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField5.requestFocus();
        return false;
    }
    
    if (containsInvalidCharacters(nama)) {
        JOptionPane.showMessageDialog(this,
            "Nama Habitat tidak boleh mengandung karakter khusus!\n" +
            "Hanya diperbolehkan: huruf, angka, spasi, koma, titik, dash (-), apostrof (')",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField5.requestFocus();
        return false;
    }
    
    if (nama.length() < 3) {
        JOptionPane.showMessageDialog(this,
            "Nama Habitat minimal 3 karakter!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField5.requestFocus();
        return false;
    }
    
    if (nama.length() > 100) {
        JOptionPane.showMessageDialog(this,
            "Nama Habitat maksimal 100 karakter!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField5.requestFocus();
        return false;
    }
    
    // ========== VALIDASI LOKASI ==========
    if (lokasi.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Lokasi harus diisi!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField6.requestFocus();
        return false;
    }
    
    if (containsInvalidCharacters(lokasi)) {
        JOptionPane.showMessageDialog(this,
            "Lokasi tidak boleh mengandung karakter khusus!\n" +
            "Hanya diperbolehkan: huruf, angka, spasi, koma, titik, dash (-)",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField6.requestFocus();
        return false;
    }
    
    if (lokasi.length() < 3) {
        JOptionPane.showMessageDialog(this,
            "Lokasi minimal 3 karakter!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField6.requestFocus();
        return false;
    }
    
    // ========== VALIDASI TIPE EKOSISTEM ==========
    if (ekosistem.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Tipe Ekosistem harus diisi!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField7.requestFocus();
        return false;
    }
    
    if (containsInvalidCharacters(ekosistem)) {
        JOptionPane.showMessageDialog(this,
            "Tipe Ekosistem tidak boleh mengandung karakter khusus!\n" +
            "Hanya diperbolehkan: huruf, angka, spasi",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField7.requestFocus();
        return false;
    }
    
    if (ekosistem.length() < 3) {
        JOptionPane.showMessageDialog(this,
            "Tipe Ekosistem minimal 3 karakter!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField7.requestFocus();
        return false;
    }
    
    // ========== VALIDASI LUAS AREA ==========
    if (luasText.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Luas Area harus diisi!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField8.requestFocus();
        return false;
    }
    
    if (!isValidNumber(luasText)) {
        JOptionPane.showMessageDialog(this,
            "Luas Area harus berupa angka!\n" +
            "Contoh: 100 atau 100.5",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField8.requestFocus();
        return false;
    }
    
    try {
        double luas = Double.parseDouble(luasText);
        
        if (luas <= 0) {
            JOptionPane.showMessageDialog(this,
                "Luas Area harus lebih dari 0!",
                "Validasi Gagal",
                JOptionPane.WARNING_MESSAGE);
            jTextField8.requestFocus();
            return false;
        }
        
        if (luas > 999999.99) {
            JOptionPane.showMessageDialog(this,
                "Luas Area maksimal 999999.99!",
                "Validasi Gagal",
                JOptionPane.WARNING_MESSAGE);
            jTextField8.requestFocus();
            return false;
        }
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
            "Format Luas Area tidak valid!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jTextField8.requestFocus();
        return false;
    }
    
    // ========== VALIDASI KONDISI ==========
    if (jComboBox1.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this,
            "Kondisi harus dipilih!",
            "Validasi Gagal",
            JOptionPane.WARNING_MESSAGE);
        jComboBox1.requestFocus();
        return false;
    }
    
    return true;
}
     
    private String getFieldText(JTextField field) {
    String text = field.getText().trim();
    if (text.equals("Nama habitat") || text.equals("Lokasi") || 
        text.equals("Ekosistem") || text.equals("Luas")) {
        return "";
    }
    return text;
    }
    
