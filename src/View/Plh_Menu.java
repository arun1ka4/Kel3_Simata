    private void handleLogout() {
        int confirm = JOptionPane.showConfirmDialog(this,
            "Apakah Anda yakin ingin logout?",
            "Konfirmasi Logout",
            JOptionPane.YES_NO_OPTION);
        
        if (confirm == JOptionPane.YES_OPTION) {
            SessionManager.getInstance().logout();
            this.dispose();
            new MenuLogin().setVisible(true);
        }
    }
    
    private void handleFilter(){
        java.util.Date tanggalDipilih = jDateChooser1.getDate();
        if (tanggalDipilih == null) {
            JOptionPane.showMessageDialog(this, 
                    "Pilih tanggal pemeliharaan terlebih dahulu!", 
                    "Validasi", 
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        PetugasPemeliharaan petugas = SessionManager.getInstance().getCurrentPetugasPemeliharaan();
        
        if (petugas != null) {
            List<Pemeliharaan> listPemeliharaan = Pemeliharaan.getPemeliharaanByPetugas(petugas.getIdPetugasPemeliharaan());
            java.sql.Date sqlTanggal = new java.sql.Date(tanggalDipilih.getTime());
            
            for (Pemeliharaan p : listPemeliharaan) {
                if (p.getTanggalPemeliharaan().equals(sqlTanggal)) {
                    Object[] row = {
                        p.getIdPemeliharaan(),
                        p.getTanggalPemeliharaan(),
                        p.getKegiatan(),
                        p.getHasilPemeliharaan(),
                        p.getStatusVerifikasi(),
                        p.getTanggalVerifikasi(),
                        p.getKeterangan()
                    };
                    model.addRow(row);
                }
            }
            if (model.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this, 
                        "Tidak ada data pemeliharaan pada tanggal tersebut.", 
                        "Informasi",
                        JOptionPane.INFORMATION_MESSAGE);
            }
        }
    }
    
