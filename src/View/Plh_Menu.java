    private void setupTable() {
        jTable1.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        jTable1.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && jTable1.getSelectedRow() >= 0) {
                loadSelectedRow();
            }
        });
    }
    
    private void loadTableData() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        // Get current petugas pemeliharaan
        PetugasPemeliharaan petugas = SessionManager.getInstance().getCurrentPetugasPemeliharaan();
        if (petugas != null) {
            List<Pemeliharaan> listPemeliharaan = 
                Pemeliharaan.getPemeliharaanByPetugas(petugas.getIdPetugasPemeliharaan());
            
            for (Pemeliharaan p : listPemeliharaan) {
                Object[] row = {
                    p.getIdPemeliharaan(),
                    p.getTanggalPemeliharaan(),
                    p.getKegiatan(),
                    p.getHasilPemeliharaan(),
                    p.getStatusVerifikasi(),
                    p.getTanggalVerifikasi(),
                    p.getKeterangan()
                };
                model.addRow(row);
            }
        }
    }
    
    private void loadSelectedRow() {
        int row = jTable1.getSelectedRow();
        if (row >= 0) {
            selectedPemeliharaanId = (int) jTable1.getValueAt(row, 0);
        }
    }
    

