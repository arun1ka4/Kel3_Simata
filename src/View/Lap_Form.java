    private void removePlaceholder(JTextField field, String placeholder) {
        field.addFocusListener(new java.awt.event.FocusAdapter() {
            public void focusGained(java.awt.event.FocusEvent evt) {
                if (field.getText().equals(placeholder)) {
                    field.setText("");
                }
            }
            public void focusLost(java.awt.event.FocusEvent evt) {
                if (field.getText().trim().isEmpty()) {
                    field.setText(placeholder);
                }
            }
        });
    }
    
    private void loadPengamatanData() {
        try {
            java.sql.Connection conn = Koneksi.getKoneksi();
            String query = "SELECT * FROM pengamatan WHERE id_pengamatan = ?";
            java.sql.PreparedStatement ps = conn.prepareStatement(query);
            ps.setInt(1, pengamatanId);
            java.sql.ResultSet rs = ps.executeQuery();
            
            if (rs.next()) {
                jTextField7.setText(String.valueOf(rs.getInt("jumlah_teramati")));
                jTextArea1.setText(rs.getString("perilaku_satwa"));
                jTextArea2.setText(rs.getString("kondisi_lingkungan"));
                jTextArea3.setText(rs.getString("catatan_tambahan"));
            }
            
            rs.close();
            ps.close();
            Koneksi.closeKoneksi();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Error loading data: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
        }
    }

