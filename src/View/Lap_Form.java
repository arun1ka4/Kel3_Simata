    private void handleSimpan() {
        if (!validateInput()) return;
        
        try {
            PetugasLapangan petugas = SessionManager.getInstance().getCurrentPetugasLapangan();
            if (petugas == null) {
                JOptionPane.showMessageDialog(this,
                    "Session tidak valid!",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            Pengamatan pengamatan = new Pengamatan();
            
            java.util.Date tanggalDipilih = jDateChooser1.getDate();
            if (tanggalDipilih == null) {
                JOptionPane.showMessageDialog(this,
                        "Tanggal pengamatan harus diisi!",
                        "Validasi",
                        JOptionPane.WARNING_MESSAGE);
                return;
            }
            Date tanggalSQL = new Date(tanggalDipilih.getTime());
            pengamatan.setTanggalPengamatan(tanggalSQL);
            pengamatan.setIdPetugasLapangan(petugas.getIdPetugasLapangan());

            pengamatan.setIdHabitat(1);
            pengamatan.setIdSatwa(1);
            
            String jumlahText = getFieldText(jTextField7);
            int jumlah = jumlahText.isEmpty() ? 0 : Integer.parseInt(jumlahText);
            pengamatan.setJumlahTeramati(jumlah);
            
            pengamatan.setPerilakuSatwa(jTextArea1.getText().trim());
            pengamatan.setKondisiLingkungan(jTextArea2.getText().trim());
            pengamatan.setCatatanTambahan(jTextArea3.getText().trim());
            
            if (isEditMode) {
                pengamatan.setIdPengamatan(pengamatanId);
                if (pengamatan.updatePengamatan()) {
                    JOptionPane.showMessageDialog(this,
                        "Pengamatan berhasil diupdate!",
                        "Sukses",
                        JOptionPane.INFORMATION_MESSAGE);
                    this.dispose();
                    new Lap_Menu().setVisible(true);
                }
            } else {
                if (pengamatan.tambahPengamatan()) {
                    JOptionPane.showMessageDialog(this,
                        "Pengamatan berhasil ditambahkan!",
                        "Sukses",
                        JOptionPane.INFORMATION_MESSAGE);
                    this.dispose();
                    new Lap_Menu().setVisible(true);
                }
            }
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Jumlah teramati harus berupa angka!",
                "Error",
                JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private boolean validateInput() {
        String jumlah = getFieldText(jTextField7);
        
        if (jumlah.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Jumlah teramati harus diisi!",
                "Validasi",
                JOptionPane.WARNING_MESSAGE);
            return false;
        }
        
        return true;
    }
    
    private String getFieldText(JTextField field) {
        String text = field.getText().trim();
        if (text.equals("Jumlah")) {
            return "";
        }
        return text;
    }
