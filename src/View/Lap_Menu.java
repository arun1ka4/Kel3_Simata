    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // Button Lihat Detail
        if (selectedPengamatanId == -1) {
            JOptionPane.showMessageDialog(this,
                "Pilih laporan untuk melihat detail!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int row = jTable1.getSelectedRow();
        if (row >= 0) {
            String detail = "Detail Laporan:\n\n" +
                "ID: " + jTable1.getValueAt(row, 0) + "\n" +
                "Tanggal: " + jTable1.getValueAt(row, 1) + "\n" +
                "Perilaku Satwa: " + jTable1.getValueAt(row, 2) + "\n" +
                "Kondisi: " + jTable1.getValueAt(row, 3) + "\n" +
                "Catatan: " + jTable1.getValueAt(row, 4) + "\n" +
                "Status: " + jTable1.getValueAt(row, 5);
            
            JOptionPane.showMessageDialog(this,
                detail,
                "Detail Laporan",
                JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

