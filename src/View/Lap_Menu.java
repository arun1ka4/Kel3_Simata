     private void handleLogout() {
        int confirm = JOptionPane.showConfirmDialog(this,
            "Apakah Anda yakin ingin logout?",
            "Konfirmasi Logout",
            JOptionPane.YES_NO_OPTION);
        
        if (confirm == JOptionPane.YES_OPTION) {
            SessionManager.getInstance().logout();
            this.dispose();
            new MenuLogin().setVisible(true);
        }
    }
    private void handleFilter() {
        
        String lokasi = jTextField2.getText().trim();
        if (lokasi.equals("Lokasi")) lokasi = "";
        
        java.util.Date tanggalDipilih = jDateChooser1.getDate();
        
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        PetugasLapangan petugas = SessionManager.getInstance().getCurrentPetugasLapangan();
        if (petugas == null) return;
        
        List<Pengamatan> listPengamatan = Pengamatan.getAllPengamatan();
        
        for (Pengamatan p : listPengamatan) {
            if (p.getIdPetugasLapangan() != petugas.getIdPetugasLapangan()) continue;
            boolean cocokLokasi = lokasi.equals("Lokasi") || lokasi.isEmpty() ||
                    (p.getLokasi() != null && p.getLokasi().toLowerCase().contains(lokasi.toLowerCase()));
            boolean cocokTanggal = tanggalDipilih == null ||
                    (p.getTanggalPengamatan() != null &&
                    p.getTanggalPengamatan().compareTo(new java.sql.Date(tanggalDipilih.getTime())) == 0);
            if (cocokLokasi && cocokTanggal) {
                Object[] row = {
                        p.getIdPengamatan(),
                        p.getTanggalPengamatan(),
                        p.getPerilakuSatwa(),
                        p.getKondisiLingkungan(),
                        p.getCatatanTambahan(),
                        p.getStatusVerifikasi(),
                        p.getTanggalVerifikasi(),
                        ""
                    };
                    model.addRow(row);
                }
            }
        
    }
