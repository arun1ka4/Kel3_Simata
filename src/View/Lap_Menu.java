    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed
        // TODO add your handling code here:
        if (selectedPengamatanId == -1) {
            JOptionPane.showMessageDialog(this,
                "Pilih laporan yang ingin dihapus!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Check if status is still "Menunggu"
        int row = jTable1.getSelectedRow();
        String status = (String) jTable1.getValueAt(row, 5);
        
        if (!status.equals("Menunggu")) {
            JOptionPane.showMessageDialog(this,
                "Hanya laporan dengan status 'Menunggu' yang dapat dihapus!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this,
            "Apakah Anda yakin ingin menghapus laporan ini?",
            "Konfirmasi Hapus",
            JOptionPane.YES_NO_OPTION);
        
        if (confirm == JOptionPane.YES_OPTION) {
            if (Pengamatan.hapusPengamatan(selectedPengamatanId)) {
                JOptionPane.showMessageDialog(this,
                    "Laporan berhasil dihapus!",
                    "Sukses",
                    JOptionPane.INFORMATION_MESSAGE);
                selectedPengamatanId = -1;
                loadTableData();
            }
        }
    }//GEN-LAST:event_jButton8ActionPerformed

