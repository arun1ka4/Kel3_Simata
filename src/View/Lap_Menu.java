    private void setupTable() {
        jTable1.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        jTable1.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && jTable1.getSelectedRow() >= 0) {
                loadSelectedRow();
            }
        });
    }
    
    private void loadTableData() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        // Get current petugas lapangan
        PetugasLapangan petugas = SessionManager.getInstance().getCurrentPetugasLapangan();
        if (petugas != null) {
            List<Pengamatan> listPengamatan = Pengamatan.getAllPengamatan();
            
            for (Pengamatan p : listPengamatan) {
                // Filter by current petugas
                if (p.getIdPetugasLapangan() == petugas.getIdPetugasLapangan()) {
                    Object[] row = {
                        p.getIdPengamatan(),
                        p.getTanggalPengamatan(),
                        p.getPerilakuSatwa(),
                        p.getKondisiLingkungan(),
                        p.getCatatanTambahan(),
                        p.getStatusVerifikasi(),
                        p.getTanggalVerifikasi(),
                        "" // Keterangan
                    };
                    model.addRow(row);
                }
            }
        }
    }
    
    private void loadSelectedRow() {
        int row = jTable1.getSelectedRow();
        if (row >= 0) {
            selectedPengamatanId = (int) jTable1.getValueAt(row, 0);
        }
    }

